import assert from "node:assert/strict";
import {chromium} from "playwright";
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--use-gl=angle","--use-angle=swiftshader","--enable-webgl","--disable-gpu-sandbox"]});
const errors=[];
const watch=page=>{
 page.on("pageerror",e=>errors.push("JS: "+e.message));
 page.on("console",m=>{if(m.type()==="error")errors.push("Console: "+m.text());});
 page.on("requestfailed",r=>errors.push("Request: "+r.url()+" "+r.failure()?.errorText));
};
try{
 const desktop=await browser.newPage({viewport:{width:1120,height:700},deviceScaleFactor:1});
 watch(desktop);
 await desktop.goto("http://127.0.0.1:8080/games/lantern-vale/",{waitUntil:"domcontentloaded"});
 await desktop.waitForFunction(()=>document.getElementById("boot")?.hidden===true,{timeout:15000});
 assert.equal(await desktop.locator("#intro").isVisible(),true);
 assert.equal(await desktop.locator("#stage").isVisible(),true);
 const init=await desktop.evaluate(()=>duoforge2dDiagnostics());
 assert.match(init.backend,/WebGL2|Canvas2D/);
 assert.ok(init.viewport>=310&&init.viewport<=960);
 await desktop.screenshot({path:"duoforge-2d-desktop.png"});
 await desktop.locator("#start").click();
 assert.equal(await desktop.locator("#intro").isVisible(),false);
 await desktop.keyboard.down("d");
 await desktop.waitForFunction(()=>duoforge2dDiagnostics().x>110,{timeout:35000});
 await desktop.keyboard.down("Space");
 await desktop.waitForFunction(()=>duoforge2dDiagnostics().jumps>0,{timeout:35000});
 await desktop.keyboard.up("Space");
 await desktop.keyboard.up("d");
 const moved=await desktop.evaluate(()=>duoforge2dDiagnostics());
 assert.ok(moved.x>110);
 assert.ok(moved.jumps>=1);
 await desktop.screenshot({path:"duoforge-2d-action.png"});
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,hasTouch:true,isMobile:true});
 watch(mobile);
 await mobile.goto("http://127.0.0.1:8080/games/lantern-vale/",{waitUntil:"domcontentloaded"});
 await mobile.waitForFunction(()=>document.getElementById("boot")?.hidden===true,{timeout:35000});
 const phone=await mobile.evaluate(()=>duoforge2dDiagnostics());
 assert.ok(phone.viewport<=390,"Portrait camera must show fewer world meters without stretching");
 await mobile.locator("#start").click();
 assert.ok(await mobile.locator("#right").isVisible());
 assert.ok(await mobile.locator("#jump").isVisible());
 await mobile.locator("#right").dispatchEvent("pointerdown",{pointerId:5});
 await mobile.waitForFunction(()=>duoforge2dDiagnostics().x>85,{timeout:35000});
 await mobile.locator("#right").dispatchEvent("pointerup",{pointerId:5});
 await mobile.locator("#jump").dispatchEvent("pointerdown",{pointerId:6});
 await mobile.waitForFunction(()=>duoforge2dDiagnostics().jumps>0,{timeout:35000});
 await mobile.locator("#jump").dispatchEvent("pointerup",{pointerId:6});
 await mobile.screenshot({path:"duoforge-2d-portrait.png"});
 assert.deepEqual(errors,[],"No WebGL shader, drawing or JS runtime errors");
 console.log("PASS: real DuoForge 2D Deluxe GPU, desktop playability, IK physics and portrait touch controls");
}finally{await browser.close()}
