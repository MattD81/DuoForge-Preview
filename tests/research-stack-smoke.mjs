import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {chromium} from "playwright";
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--use-gl=angle","--use-angle=swiftshader","--enable-webgl","--disable-gpu-sandbox"]});
try{
 const page=await browser.newPage({viewport:{width:1220,height:840},acceptDownloads:true});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto("http://127.0.0.1:8080/workshop/studio/",{waitUntil:"domcontentloaded"});
 await page.waitForFunction(()=>document.querySelector("#objectCount")?.textContent==="1",{timeout:30000});
 assert.equal(await page.locator("#freeResearchLab").count(),1,"Mounts in existing Studio");
 await page.locator("#stackHealth").click();
 assert.match(await page.locator("#stackInfo").textContent(),/Scenkontroll:.*trianglar.*WebGL/);
 const [dl]=await Promise.all([page.waitForEvent("download"),page.locator("#exportGLB").click()]);
 const original=readFileSync(await dl.path());
 await page.locator("#stackImport").setInputFiles({name:"testmodell.glb",mimeType:"model/gltf-binary",buffer:original});
 await page.waitForFunction(()=>document.querySelector("#stackInfo")?.textContent.includes("GLB:"));
 assert.match(await page.locator("#stackInfo").textContent(),/GLB:.*meshar/);
 await page.locator("#stackIndex").click();
 await page.waitForFunction(()=>document.querySelector("#stackInfo")?.textContent.includes("indexerad."),{timeout:30000});
 assert.equal(await page.locator("#stackAssets .saved-row").count(),1);
 await page.locator("#stackIndex").click();
 await page.waitForFunction(()=>document.querySelector("#stackInfo")?.textContent.includes("Ingen kopia skapad"),{timeout:30000});
 assert.equal(await page.locator("#stackAssets .saved-row").count(),1,"Exact GLB not duplicated");
 const [json]=await Promise.all([page.waitForEvent("download"),page.locator("#stackReport").click()]);
 assert.equal(json.suggestedFilename(),"duoforge-research-report.json");
 const data=JSON.parse(readFileSync(await json.path(),"utf8"));
 assert.match(data.entry.sha256,/^[0-9a-f]{64}$/);
 assert.equal(data.entry.bytes,original.length);
 await page.locator("#stackSplat").setInputFiles({name:"bad.txt",mimeType:"text/plain",buffer:Buffer.from("BAD SPLAT DATA")});
 await page.waitForFunction(()=>document.querySelector("#stackInfo")?.textContent.includes("Splat:"));
 assert.match(await page.locator("#stackInfo").textContent(),/Välj .spz/);
 assert.deepEqual(errors,[],"No runtime exceptions in browser");
 console.log("PASS: Open Research Panel, GLB validation, indexed dedupe, report, extension guard");
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 await mobile.goto("http://127.0.0.1:8080/workshop/studio/",{waitUntil:"domcontentloaded"});
 await mobile.waitForSelector("#freeResearchLab",{timeout:30000});
 assert.equal(await mobile.locator("#stackSplat").count(),1);
 console.log("PASS: mobile Open Research Panel loads");
}finally{await browser.close();}
