/**
 * DuoForge GPU Deluxe V2 shaders.
 * Temporal history reconstruction is NOT AI/DLSS (no trained neural weights).
 * Analytic ray tracer uses bounding-sphere PROXIES, not GLB triangle geometry.
 */
export const TEMPORAL_RECONSTRUCT_SHADER={
 vertexShader:[
  "varying vec2 vUv;",
  "void main(){vUv=uv;gl_Position=vec4(position.xy,0.,1.);}"
 ].join("\n"),
 fragmentShader:[
  "precision highp float;",
  "varying vec2 vUv;",
  "uniform sampler2D tCurrent;",
  "uniform sampler2D tHistory;",
  "uniform vec2 uTexel;",
  "uniform float uHistoryWeight;",
  "void main(){",
  "vec3 c=texture2D(tCurrent,vUv).rgb;",
  "vec3 l=texture2D(tCurrent,vUv-vec2(uTexel.x,0.)).rgb;",
  "vec3 r=texture2D(tCurrent,vUv+vec2(uTexel.x,0.)).rgb;",
  "vec3 u=texture2D(tCurrent,vUv+vec2(0.,uTexel.y)).rgb;",
  "vec3 d=texture2D(tCurrent,vUv-vec2(0.,uTexel.y)).rgb;",
  "vec3 lo=min(c,min(min(l,r),min(u,d)));",
  "vec3 hi=max(c,max(max(l,r),max(u,d)));",
  "vec3 hist=clamp(texture2D(tHistory,vUv).rgb,lo,hi);",
  "vec3 sm=(c*4.+l+r+u+d)/8.;",
  "vec3 sharpen=max(c+(c-sm)*.2,vec3(0.));",
  "gl_FragColor=vec4(mix(sharpen,hist,clamp(uHistoryWeight,0.,.82)),1.);",
  "}"
 ].join("\n")
};
export const PROXY_RAYTRACE_SHADER={
 maxSpheres:12,
 vertexShader:TEMPORAL_RECONSTRUCT_SHADER.vertexShader,
 fragmentShader:[
  "precision highp float;",
  "varying vec2 vUv;",
  "uniform mat4 uCameraWorld;",
  "uniform float uFovRad;",
  "uniform float uAspect;",
  "uniform int uCount;",
  "uniform vec4 uSpheres[12];",
  "uniform vec3 uColors[12];",
  "uniform float uReflect[12];",
  "vec3 sky(vec3 rd){",
  " return mix(vec3(.04,.06,.12),vec3(.38,.63,.86),pow(max(rd.y,0.),.75));",
  "}",
  "float hitSphere(vec3 ro,vec3 rd,vec4 s){",
  " vec3 oc=ro-s.xyz;float b=dot(oc,rd);float c=dot(oc,oc)-s.w*s.w;",
  " float d=b*b-c;if(d<0.)return 1e20;",
  " float t=-b-sqrt(d);if(t>.002)return t;",
  " t=-b+sqrt(d);return t>.002?t:1e20;",
  "}",
  "vec2 trace(vec3 ro,vec3 rd){",
  " float best=1e20;float id=-2.;",
  " for(int i=0;i<12;i++){if(i>=uCount)break;",
  "  float t=hitSphere(ro,rd,uSpheres[i]);",
  "  if(t<best){best=t;id=float(i);}",
  " }",
  " if(rd.y<-.0001){float t=-ro.y/rd.y;",
  "  if(t>.002&&t<best){best=t;id=-1.;}",
  " }",
  " return vec2(best,id);",
  "}",
  "vec3 normalAt(vec3 p,float id){",
  " if(id<0.)return vec3(0.,1.,0.);",
  " for(int i=0;i<12;i++){if(i>=uCount)break;",
  "  if(abs(float(i)-id)<.5)return normalize(p-uSpheres[i].xyz);",
  " }return vec3(0.,1.,0.);",
  "}",
  "vec3 surfaceColor(vec3 p,float id){",
  " if(id<0.){float checker=mod(floor(p.x)+floor(p.z),2.);",
  "  return mix(vec3(.12,.16,.22),vec3(.23,.27,.31),checker);}",
  " for(int i=0;i<12;i++){if(i>=uCount)break;",
  "  if(abs(float(i)-id)<.5)return uColors[i];",
  " }return vec3(.65);",
  "}",
  "float reflectivity(float id){",
  " if(id<0.)return .16;",
  " for(int i=0;i<12;i++){if(i>=uCount)break;",
  "  if(abs(float(i)-id)<.5)return uReflect[i];",
  " }return 0.;",
  "}",
  "vec3 shade(vec3 ro,vec3 rd,vec2 hit){",
  " if(hit.y< -1.5)return sky(rd);",
  " vec3 p=ro+hit.x*rd;vec3 n=normalAt(p,hit.y);",
  " vec3 sun=normalize(vec3(.6,.83,.3));",
  " vec2 obstacle=trace(p+n*.015,sun);",
  " float vis=obstacle.x<1e19?.18:1.;",
  " float diffuse=max(dot(n,sun),0.);",
  " float spec=pow(max(dot(reflect(-sun,n),-rd),0.),26.);",
  " return surfaceColor(p,hit.y)*(.22+diffuse*.82*vis)+vec3(spec*.24*vis);",
  "}",
  "void main(){",
  " vec2 ndc=vUv*2.-1.;",
  " vec3 local=normalize(vec3(ndc.x*uAspect*tan(uFovRad*.5),ndc.y*tan(uFovRad*.5),-1.));",
  " vec3 rd=normalize((uCameraWorld*vec4(local,0.)).xyz);",
  " vec3 ro=uCameraWorld[3].xyz;",
  " vec2 hit=trace(ro,rd);vec3 color=shade(ro,rd,hit);",
  " if(hit.y>=-1.){",
  "  vec3 p=ro+hit.x*rd;vec3 n=normalAt(p,hit.y);",
  "  vec3 rr=normalize(reflect(rd,n));vec3 start=p+n*.015;",
  "  color=mix(color,shade(start,rr,trace(start,rr)),reflectivity(hit.y));",
  " }",
  " color=color/(color+vec3(.75));",
  " color=pow(max(color,vec3(0.)),vec3(1./2.2));",
  " gl_FragColor=vec4(color,1.);",
  "}"
 ].join("\n")
};
